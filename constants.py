HBAR_C_MEV_FM = 197.3269804             # ħc в МэВ·фм

M_E_MEV = 0.51099895000                 # Масса электрона (МэВ)
M_MU_MEV = 105.6583755                  # Масса мюона (МэВ)

# Комптоновские радиусы (ħc / mc^2)
R_E_COMPTON_FM = HBAR_C_MEV_FM / M_E_MEV      # ~386.159 фм
R_MU_COMPTON_FM = HBAR_C_MEV_FM / M_MU_MEV    # ~1.8676 фм

# Базовые масштабы нефермионного вакуума
L_VAC_FM = R_E_COMPTON_FM * np.sqrt(ALPHA_FS) # Характерный масштаб короны (~33.0 фм) или через r_e / alpha
R_CORE_VAC_FM = R_E_COMPTON_FM * ALPHA_FS     # Масштаб керна (~2.818 фм)

